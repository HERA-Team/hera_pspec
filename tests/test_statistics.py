"""Physical and statistical checks of the power spectrum estimators.

The tests in this module check that the estimators give the *right numbers*
(correct amplitudes, unbiased means, calibrated errors, exact algebraic
identities), not just that the code runs. They use synthetic visibilities with a
known statistical model, generated by ``hera_pspec.testing.synthetic_uvdata``.
Many integrations of a single baseline are used as independent realisations of
the noise, so a single call to ``PSpecData.pspec`` gives thousands of draws.

Statistical assertions compare a sample mean with its expectation within K_SIGMA
standard errors, where the standard error is estimated from the scatter of the
draws themselves (one draw per integration, since the noise is independent
between integrations). The random seeds are fixed, so the tests are
deterministic; each statistical test was also run with several other seeds to
make sure that the tolerances are not tuned to a lucky draw.
"""

import copy

import numpy as np
import pytest

from hera_pspec import PSpecBeamGauss, PSpecData, UVPSpec, grouping, testing, utils
from hera_pspec.uvpspec import combine_uvpspec

# Number of standard errors allowed between a sample mean and its expectation.
# For a Gaussian sample mean, a 5-sigma deviation has a probability of ~6e-7.
K_SIGMA = 5

# Seed of the white-noise and coloured-noise visibilities below.
NOISE_SEED = 10

# Number of channels and integrations of the synthetic noise used to check the
# amplitude of the power spectra.
NFREQ = 16
NTIMES = 2000


@pytest.fixture(scope="module")
def white_noise_uvd(synthetic_uvd):
    """White complex Gaussian noise with E|x|^2 = 1 on one baseline.

    NFREQ channels x NTIMES integrations, so a pspec() call gives NTIMES
    independent spectra.
    """
    return synthetic_uvd(nfreq=NFREQ, ntimes=NTIMES, antpairs=[(0, 1)], seed=NOISE_SEED)


@pytest.fixture(scope="module")
def gauss_beam():
    return PSpecBeamGauss(0.2, np.linspace(140e6, 170e6, 100))


@pytest.fixture(scope="module")
def untapered_scalar(white_noise_uvd, gauss_beam) -> float:
    """Beam/cosmology scalar of the full band without a taper.

    This converts power in "telescope units" (mK^2 per delay mode) to
    cosmological units. A correctly calibrated estimator returns
    E[P] = untapered_scalar * p for a band power p, whatever the taper, since the
    taper only changes how the band power is estimated, not its value.
    """
    ds = PSpecData(dsets=[white_noise_uvd], wgts=[None], beam=gauss_beam)
    ds.set_spw((0, NFREQ))
    return ds.scalar(("xx", "xx"), taper_override="none")


def auto_pspec(uvd, beam, **kwargs) -> UVPSpec:
    """Power spectrum of baseline (0, 1) of ``uvd`` with itself."""
    ds = PSpecData(dsets=[uvd, uvd], wgts=[None, None], beam=beam)
    return ds.pspec(
        [(0, 1)], [(0, 1)], dsets=(0, 1), pols=[("xx", "xx")], verbose=False, **kwargs
    )


def mean_and_error(values: np.ndarray, axis: int | None = None):
    """Mean over the first (time) axis and its standard error.

    If ``axis`` is None, all other axes are averaged first, so the mean is over
    all values and the standard error accounts for correlations along the other
    axes (e.g. between delays, which a taper correlates).
    """
    if axis is None:
        values = values.reshape(len(values), -1).mean(axis=1)
    return values.mean(axis=0), values.std(axis=0, ddof=1) / np.sqrt(len(values))


def assert_within_errors(mean, expected, error, k=K_SIGMA):
    """Assert that ``mean`` is within ``k`` standard errors of ``expected``."""
    pull = (np.asarray(mean) - expected) / error
    assert np.all(np.abs(pull) < k), f"deviation of {pull} standard errors"


XFAIL_I_FEWER_DELAYS = pytest.mark.xfail(
    strict=True, reason="amplitude scales with n_dlys/Nfreqs, see #548"
)
XFAIL_H_FEWER_DELAYS_TAPER = pytest.mark.xfail(
    strict=True,
    reason=(
        "With n_dlys < Nfreqs the delay modes repeat every n_dlys channels, so "
        "white noise is not a flat band power of the model; with a taper the "
        "H^-1 and V^-1/2 white-noise power is ~2x too high (bh)"
    ),
)
XFAIL_H_FEWER_DELAYS_SAMPLING = pytest.mark.xfail(
    strict=True,
    reason=(
        "With n_dlys < Nfreqs and sampling=False the H^-1 and V^-1/2 "
        "white-noise power is ~1.3x too high"
    ),
)


def _fewer_delays_cases():
    """(norm, taper, sampling) cases with n_dlys < Nfreqs and their known failures."""
    cases = []
    for norm in ["I", "H^-1", "V^-1/2"]:
        for taper in ["none", "bh"]:
            for sampling in [True, False]:
                if norm == "I":
                    marks = [XFAIL_I_FEWER_DELAYS]
                elif taper != "none":
                    marks = [XFAIL_H_FEWER_DELAYS_TAPER]
                elif not sampling:
                    marks = [XFAIL_H_FEWER_DELAYS_SAMPLING]
                else:
                    marks = []
                cases.append(
                    pytest.param(
                        norm,
                        taper,
                        sampling,
                        marks=marks,
                        id=f"{norm}-{taper}-sampling_{sampling}",
                    )
                )
    return cases


class TestWhiteNoiseCalibration:
    """White noise with E|x|^2 = sigma^2 in every channel has a flat band power
    of sigma^2 / Nfreqs per delay mode. So the calibrated power spectrum must be

        E[P] = scalar(taper='none') * sigma^2 / Nfreqs

    at every delay, independently of the normalization, the taper, the sampling
    assumption, the number of delays and of flagged channels. A wrong factor in
    the normalization matrix M, a taper that is accounted for twice (or not at
    all) or mishandled flags would all change the amplitude. (The scalar itself
    is checked against its analytic form in test_pspecbeam.py.)
    """

    @pytest.mark.parametrize("sampling", [True, False])
    @pytest.mark.parametrize("taper", ["none", "bh", "blackman", "hann"])
    @pytest.mark.parametrize("norm", ["I", "H^-1", "V^-1/2"])
    def test_white_noise_power(
        self, white_noise_uvd, gauss_beam, untapered_scalar, norm, taper, sampling
    ) -> None:
        """The calibrated white-noise power is correct for every normalization
        and taper, with one delay mode per channel."""
        uvp = auto_pspec(
            white_noise_uvd, gauss_beam, norm=norm, taper=taper, sampling=sampling
        )
        power = uvp.data_array[0][:, :, 0].real / untapered_scalar
        mean, error = mean_and_error(power)
        assert_within_errors(mean, 1 / NFREQ, error)

    @pytest.mark.parametrize("taper", ["none", "bh"])
    @pytest.mark.parametrize("norm", ["I", "H^-1", "V^-1/2"])
    def test_white_noise_power_with_flagged_channels(
        self, white_noise_uvd, gauss_beam, untapered_scalar, norm, taper
    ) -> None:
        """Flagging a few channels removes data but does not change the
        calibrated power: the normalization accounts for the flagged
        channels."""
        uvd = white_noise_uvd.copy()
        uvd.flag_array[:, [3, 4, 5, 12], :] = True
        uvp = auto_pspec(uvd, gauss_beam, norm=norm, taper=taper)
        power = uvp.data_array[0][:, :, 0].real / untapered_scalar
        mean, error = mean_and_error(power)
        assert_within_errors(mean, 1 / NFREQ, error)

    @pytest.mark.parametrize("norm,taper,sampling", _fewer_delays_cases())
    def test_white_noise_power_with_fewer_delays(
        self, white_noise_uvd, gauss_beam, untapered_scalar, norm, taper, sampling
    ) -> None:
        """Estimating fewer delay modes than channels (wider delay bins) does
        not change the power of a flat spectrum."""
        uvp = auto_pspec(
            white_noise_uvd,
            gauss_beam,
            norm=norm,
            taper=taper,
            sampling=sampling,
            n_dlys=[NFREQ // 4],
        )
        power = uvp.data_array[0][:, :, 0].real / untapered_scalar
        mean, error = mean_and_error(power)
        assert_within_errors(mean, 1 / NFREQ, error)


class TestColouredSpectrumIsUnbiased:
    """For a band power spectrum p, the estimator is unbiased in the sense that
    E[P] = scalar(taper='none') * W p, where W is the window function it
    reports. This is the defining property of the quadratic estimator.

    The visibilities are drawn with covariance C = sum_b p_b Q_b, where Q_b is
    the response of the covariance to the band power at delay b
    (utils.get_Q_alt). The spectrum peaks at a positive delay, so the test also
    pins the sign convention of the delay axis: a fringe exp(+2 pi i nu tau)
    appears at delay +tau, and a flipped delay axis would fail.
    """

    @pytest.fixture(scope="class")
    def band_powers(self) -> np.ndarray:
        dly_index = np.arange(NFREQ) - NFREQ // 2
        return 0.05 + np.exp(-0.5 * ((dly_index - 3) / 1.5) ** 2)

    @pytest.fixture(scope="class")
    def coloured_uvd(self, synthetic_uvd, band_powers):
        freq_cov = sum(
            p * utils.get_Q_alt(b, NFREQ, NFREQ) for b, p in enumerate(band_powers)
        )
        uvd = synthetic_uvd(
            nfreq=NFREQ,
            ntimes=NTIMES,
            antpairs=[(0, 1)],
            freq_cov=freq_cov,
            seed=NOISE_SEED,
        )
        # The covariance is that of fringes exp(+2 pi i nu tau) with power p(tau)
        # at the delays of the power spectrum.
        freqs = uvd.freq_array
        fringes = np.exp(2j * np.pi * np.outer(freqs, utils.get_delays(freqs)))
        np.testing.assert_allclose(
            freq_cov, (fringes * band_powers) @ fringes.conj().T, atol=1e-10
        )
        return uvd

    @pytest.mark.parametrize("taper", ["none", "bh"])
    @pytest.mark.parametrize("norm", ["I", "H^-1"])
    def test_mean_power_is_window_function_times_band_powers(
        self, coloured_uvd, gauss_beam, untapered_scalar, band_powers, norm, taper
    ) -> None:
        """The mean power at every delay equals W p within the statistical
        errors, and the peak is at a positive delay."""
        uvp = auto_pspec(
            coloured_uvd, gauss_beam, norm=norm, taper=taper, sampling=True
        )
        power = uvp.data_array[0][:, :, 0].real / untapered_scalar
        window = uvp.window_function_array[0][0, :, :, 0]
        mean, error = mean_and_error(power, axis=0)
        assert_within_errors(mean, window @ band_powers, error)
        assert uvp.get_dlys(0)[np.argmax(mean)] > 0


class TestEstimatorIdentities:
    """Exact algebraic identities of the quadratic estimator, which hold to
    numerical precision for any data."""

    @pytest.fixture(scope="class")
    def uvd(self, synthetic_uvd):
        return synthetic_uvd(nfreq=NFREQ, ntimes=5, antpairs=[(0, 1)], seed=1)

    @pytest.mark.parametrize("allow_fft", [False, True])
    def test_parseval(self, uvd, allow_fft: bool) -> None:
        """With identity weighting, no taper and one delay per channel, the
        unnormalized band powers add up to the total power of the data,
        sum_a q_a = N/2 sum_i |x_i|^2 (Parseval's theorem with the factor 1/2
        of the q_hat definition). This pins the overall normalization of q_hat.
        """
        ds = PSpecData(dsets=[uvd, uvd], wgts=[None, None])
        key = (0, (0, 1), "xx")
        q = ds.q_hat(key, key, allow_fft=allow_fft)
        x = ds.x(key)
        np.testing.assert_allclose(
            q.sum(axis=0), 0.5 * NFREQ * np.sum(np.abs(x) ** 2, axis=0), rtol=1e-10
        )

    @pytest.mark.parametrize("allow_fft", [False, True])
    @pytest.mark.parametrize("nfreq", [15, 16])
    def test_delay_modes_are_complete(self, nfreq: int, allow_fft: bool) -> None:
        """With one delay per channel, the Q_alt matrices add up to N times the
        identity: the delay modes form a complete orthogonal basis, so a flat
        band power is white noise."""
        total = sum(
            utils.get_Q_alt(b, nfreq, nfreq, allow_fft=allow_fft) for b in range(nfreq)
        )
        np.testing.assert_allclose(total, nfreq * np.eye(nfreq), atol=1e-10)

    @pytest.mark.parametrize("taper", ["none", "bh"])
    def test_fisher_matrix_is_trace_of_e_and_q(self, uvd, taper: str) -> None:
        """G_ab = Tr[E_a Q_b], with E_a = R_1^dagger Q_a R_2 / 2 from
        get_unnormed_E, so that E[q_a] = sum_b G_ab p_b for C = sum_b p_b Q_b.

        The two datasets have different flags, so R_1 != R_2 and a transposed or
        misplaced R would break the identity.
        """
        uvd2 = uvd.copy()
        uvd2.flag_array[:, [2, 9], :] = True
        ds = PSpecData(dsets=[uvd, uvd2], wgts=[None, None])
        ds.set_taper(taper)
        key1, key2 = (0, (0, 1), "xx"), (1, (0, 1), "xx")
        G = ds.get_G(key1, key2)
        E = ds.get_unnormed_E(key1, key2)
        Q = np.array([ds.get_Q_alt(b) for b in range(NFREQ)])
        trace = np.einsum("aij,bji->ab", E, Q)
        np.testing.assert_allclose(G, trace, rtol=0, atol=1e-10 * np.abs(G).max())


class TestPspecSymmetries:
    """Symmetries of the power spectrum under exchange and rescaling of the
    inputs. P = x_1^dagger E x_2 is linear in x_2 and antilinear in x_1, and
    exchanging x_1 and x_2 conjugates it. These catch conjugation and ordering
    mistakes in the handling of baseline pairs and datasets in pspec()."""

    @pytest.fixture(scope="class")
    def uvds(self, synthetic_uvd):
        kwargs = dict(nfreq=NFREQ, ntimes=20, antpairs=[(0, 1), (1, 2)])
        return synthetic_uvd(seed=1, **kwargs), synthetic_uvd(seed=2, **kwargs)

    @staticmethod
    def cross_pspec(uvd1, uvd2, bl1, bl2, norm, taper="bh") -> np.ndarray:
        ds = PSpecData(dsets=[uvd1, uvd2], wgts=[None, None])
        uvp = ds.pspec(
            [bl1],
            [bl2],
            dsets=(0, 1),
            pols=[("xx", "xx")],
            norm=norm,
            taper=taper,
            verbose=False,
        )
        return uvp.data_array[0][:, :, 0]

    @pytest.mark.parametrize("norm", ["I", "H^-1"])
    def test_swapping_inputs_conjugates(self, uvds, norm: str) -> None:
        """Exchanging the baselines and the datasets conjugates the cross
        spectrum."""
        uvd1, uvd2 = uvds
        P12 = self.cross_pspec(uvd1, uvd2, (0, 1), (1, 2), norm)
        P21 = self.cross_pspec(uvd2, uvd1, (1, 2), (0, 1), norm)
        np.testing.assert_allclose(
            P21, P12.conj(), rtol=0, atol=1e-12 * np.abs(P12).max()
        )

    @pytest.mark.parametrize("norm", ["I", "H^-1"])
    def test_scaling_inputs(self, uvds, norm: str) -> None:
        """Scaling the first dataset by a complex factor a multiplies P by
        conj(a); scaling both multiplies it by |a|^2."""
        uvd1, uvd2 = uvds
        a = 2.0 - 1.0j
        scaled1, scaled2 = uvd1.copy(), uvd2.copy()
        scaled1.data_array *= a
        scaled2.data_array *= a
        P = self.cross_pspec(uvd1, uvd2, (0, 1), (1, 2), norm)
        atol = 1e-12 * np.abs(P).max() * abs(a) ** 2
        np.testing.assert_allclose(
            self.cross_pspec(scaled1, uvd2, (0, 1), (1, 2), norm),
            np.conj(a) * P,
            rtol=0,
            atol=atol,
        )
        np.testing.assert_allclose(
            self.cross_pspec(scaled1, scaled2, (0, 1), (1, 2), norm),
            abs(a) ** 2 * P,
            rtol=0,
            atol=atol,
        )

    def test_auto_spectra_are_real_and_positive(self, uvds) -> None:
        """The power spectrum of a baseline with itself is |x~|^2 per delay
        (identity weighting, no taper): real and non-negative."""
        uvd1, _ = uvds
        P = self.cross_pspec(uvd1, uvd1, (0, 1), (0, 1), "I", taper="none")
        assert np.all(P.real > 0)
        assert np.all(np.abs(P.imag) < 1e-10 * P.real)


class TestAveragingStatistics:
    """average_spectra must return the weighted mean of the spectra, with the
    errors and covariances of that weighted mean.

    For spectra P_i with weights w_i (per delay), the average is
    sum_i w_i P_i / sum_i w_i. If the P_i are independent with covariances C_i,
    the covariance of the average is sum_i w_i w_i^T C_i / (sum_i w_i)^2. With
    inverse-variance weights w_i = 1 / sigma_i^2 the error on the average is
    (sum_i sigma_i^-2)^-1/2, the smallest possible. By default the weights are
    w_i = t_int^2 * nsamples (the inverse square of the noise power).
    """

    BLPAIRS = [101102101102, 102103102103, 101103101103]

    @pytest.fixture
    def uvp(self) -> UVPSpec:
        """Three baseline pairs of random spectra, with random errors,
        covariances, integration times and nsamples."""
        uvp, _ = testing.build_vanilla_uvpspec(data="random", seed=5)
        rng = np.random.default_rng(6)
        shape = uvp.data_array[0].shape
        uvp.stats_array = {"err": {0: (0.5 + rng.random(shape)).astype(complex)}}
        # random positive definite covariances
        A = rng.standard_normal((shape[0], shape[1], shape[1], 1))
        uvp.cov_array_real[0] = np.einsum("tikp,tjkp->tijp", A, A) / shape[1]
        uvp.integration_array[0] = 5 + 10 * rng.random(uvp.integration_array[0].shape)
        uvp.nsample_array[0] = rng.integers(1, 4, uvp.nsample_array[0].shape).astype(
            float
        )
        return uvp

    @staticmethod
    def stack(uvp, getter, *args):
        """Stack a per-blpair quantity over the three baseline pairs."""
        return np.array(
            [
                getattr(uvp, getter)(*args, (0, blp, ("xx", "xx")))
                for blp in TestAveragingStatistics.BLPAIRS
            ]
        )

    def average(self, uvp, time_avg, **kwargs):
        return grouping.average_spectra(
            uvp,
            blpair_groups=[self.BLPAIRS],
            time_avg=time_avg,
            error_field="err",
            inplace=False,
            **kwargs,
        )

    @staticmethod
    def expected_average(weights, data, cov, time_avg):
        """Weighted mean of data (Nblpairs, Ntimes, Ndlys) and its covariance."""
        axes = (0, 1) if time_avg else (0,)
        wsum = weights.sum(axis=axes)
        mean = (weights * data).sum(axis=axes) / wsum
        wcov = weights[..., :, None] * weights[..., None, :] * cov
        mean_cov = wcov.sum(axis=axes) / (wsum[..., :, None] * wsum[..., None, :])
        return mean, mean_cov

    def check_average(self, avg, weights, uvp, time_avg):
        data = self.stack(uvp, "get_data")
        cov = self.stack(uvp, "get_cov")
        err = self.stack(uvp, "get_stats", "err").real
        mean, mean_cov = self.expected_average(weights, data, cov, time_avg)
        # errors are propagated like the diagonal of a diagonal covariance
        _, err_cov = self.expected_average(
            weights, data, err[..., :, None] ** 2 * np.eye(uvp.Ndlys), time_avg
        )
        key = (0, self.BLPAIRS[0], ("xx", "xx"))
        shape = avg.get_data(key).shape
        np.testing.assert_allclose(avg.get_data(key), mean.reshape(shape), rtol=1e-10)
        np.testing.assert_allclose(
            avg.get_cov(key), mean_cov.reshape(avg.get_cov(key).shape), rtol=1e-10
        )
        np.testing.assert_allclose(
            avg.get_stats("err", key).real,
            np.sqrt(np.diagonal(err_cov, axis1=-2, axis2=-1)).reshape(shape),
            rtol=1e-10,
        )

    @pytest.mark.parametrize("time_avg", [False, True])
    def test_uniform_weights_give_the_mean(self, time_avg: bool) -> None:
        """With equal integration times and nsamples, the average is the plain
        mean over baseline pairs (and times)."""
        uvp, _ = testing.build_vanilla_uvpspec(data="random", seed=5)
        avg = grouping.average_spectra(
            uvp, blpair_groups=[self.BLPAIRS], time_avg=time_avg, inplace=False
        )
        data = self.stack(uvp, "get_data")
        mean = data.mean(axis=(0, 1) if time_avg else 0)
        np.testing.assert_allclose(
            avg.get_data((0, self.BLPAIRS[0], ("xx", "xx"))),
            mean.reshape(-1, uvp.Ndlys),
            rtol=1e-12,
        )

    @pytest.mark.parametrize("time_avg", [False, True])
    def test_integration_weights(self, uvp, time_avg: bool) -> None:
        """By default spectra are weighted by t_int^2 * nsamples, and the
        covariances and errors are those of the weighted mean."""
        ints = self.stack(uvp, "get_integrations")
        nsmp = self.stack(uvp, "get_nsamples")
        weights = np.repeat((ints**2 * nsmp)[..., None], uvp.Ndlys, axis=-1)
        avg = self.average(uvp, time_avg)
        self.check_average(avg, weights, uvp, time_avg)

    @pytest.mark.parametrize("time_avg", [False, True])
    def test_inverse_variance_weights(self, uvp, time_avg: bool) -> None:
        """With error_weights, each delay of each spectrum is weighted by
        1 / sigma^2, giving the inverse-variance weighted mean with error
        (sum sigma^-2)^-1/2."""
        err = self.stack(uvp, "get_stats", "err").real
        weights = 1 / err**2
        avg = self.average(uvp, time_avg, error_weights="err")
        self.check_average(avg, weights, uvp, time_avg)
        # the error on the inverse-variance weighted mean
        key = (0, self.BLPAIRS[0], ("xx", "xx"))
        axes = (0, 1) if time_avg else (0,)
        np.testing.assert_allclose(
            avg.get_stats("err", key).real,
            (weights.sum(axis=axes) ** -0.5).reshape(-1, uvp.Ndlys),
            rtol=1e-10,
        )

    @pytest.mark.parametrize(
        "time_avg,group_blpairs", [(True, False), (False, True), (True, True)]
    )
    def test_variance_reduction(self, time_avg: bool, group_blpairs: bool) -> None:
        """Averaging N independent spectra of unit variance gives a variance of
        1/N, both as propagated into the covariance and empirically.

        The empirical variance of the average is measured over 100
        realisations x 50 delays (x blpairs), so its relative standard error
        is at most sqrt(2 / 5000) = 2%.
        """
        uvp, _ = testing.build_vanilla_uvpspec(data="random", seed=0)
        # the vanilla covariances are the identity: real and imaginary parts
        # of the random data have unit variance and are independent
        assert np.all(uvp.cov_array_real[0][..., 0] == np.eye(uvp.Ndlys))
        blpair_groups = [self.BLPAIRS] if group_blpairs else None
        n_avg = (uvp.Ntimes if time_avg else 1) * (3 if group_blpairs else 1)
        rng = np.random.default_rng(7)
        averages = []
        for _ in range(100):
            uvp.data_array[0] = rng.standard_normal(
                uvp.data_array[0].shape
            ) + 1j * rng.standard_normal(uvp.data_array[0].shape)
            avg = grouping.average_spectra(
                uvp, blpair_groups=blpair_groups, time_avg=time_avg, inplace=False
            )
            averages.append(avg.data_array[0])
        averages = np.array(averages)

        for component in ["real", "imag"]:
            cov = getattr(avg, f"cov_array_{component}")[0][..., 0]
            np.testing.assert_allclose(
                cov,
                np.broadcast_to(np.eye(uvp.Ndlys) / n_avg, cov.shape),
                rtol=1e-12,
                atol=1e-15,
            )
            values = getattr(averages, component)
            variance = np.mean(values**2)
            error = np.sqrt(2 / values.size) / n_avg
            assert_within_errors(variance, 1 / n_avg, error)

    @pytest.fixture(scope="class")
    def pspec_uvp(self, synthetic_uvd) -> UVPSpec:
        """Power spectra with (tapered) window functions that are not diagonal."""
        antpairs = [(0, 1), (1, 2), (0, 2)]
        kwargs = dict(nfreq=NFREQ, ntimes=10, antpairs=antpairs)
        ds = PSpecData(
            dsets=[synthetic_uvd(seed=1, **kwargs), synthetic_uvd(seed=2, **kwargs)],
            wgts=[None, None],
        )
        uvp = ds.pspec(
            antpairs,
            antpairs,
            dsets=(0, 1),
            pols=[("xx", "xx")],
            taper="bh",
            verbose=False,
        )
        rng = np.random.default_rng(8)
        shape = uvp.data_array[0].shape
        uvp.stats_array = {"err": {0: (0.5 + rng.random(shape)).astype(complex)}}
        uvp.integration_array[0] = 5 + 10 * rng.random(uvp.integration_array[0].shape)
        return uvp

    @pytest.mark.parametrize(
        "operation",
        [
            lambda uvp: grouping.average_spectra(
                uvp,
                blpair_groups=[list(np.unique(uvp.blpair_array))],
                time_avg=True,
                inplace=False,
            ),
            lambda uvp: grouping.average_spectra(
                uvp,
                blpair_groups=[list(np.unique(uvp.blpair_array))],
                blpair_weights=[[0.5, 2.0, 1.0]],
                error_weights="err",
                inplace=False,
            ),
            lambda uvp: grouping.average_in_delay_bins(uvp, kernel=np.ones(3)),
            lambda uvp: combine_uvpspec(
                [
                    uvp.select(
                        blpairs=list(np.unique(uvp.blpair_array))[:1], inplace=False
                    ),
                    uvp.select(
                        blpairs=list(np.unique(uvp.blpair_array))[1:], inplace=False
                    ),
                ],
                verbose=False,
            ),
        ],
        ids=["time_and_blpair_average", "weighted_average", "delay_bins", "combine"],
    )
    def test_window_functions_stay_normalised(self, pspec_uvp, operation) -> None:
        """Every delay of a power spectrum is a weighted mean of band powers,
        so each row of its window function sums to one. Averaging and
        combining spectra must preserve that."""
        wf = pspec_uvp.window_function_array[0]
        assert not np.allclose(wf[..., 0], np.eye(NFREQ))
        np.testing.assert_allclose(wf.sum(axis=2), 1.0, rtol=1e-10)
        new = operation(copy.deepcopy(pspec_uvp))
        np.testing.assert_allclose(
            new.window_function_array[0].sum(axis=2), 1.0, rtol=1e-10
        )


class TestNoiseCrossSpectra:
    """Cross-spectra of two independent noise realisations (e.g. interleaved
    integrations, or different nights) have zero mean, so they carry no noise
    bias. Their real and imaginary parts scatter equally, by the thermal noise
    power P_N of noise.calc_P_N, and the analytic covariance computed from the
    noise level of the visibilities (cov_model="dsets") must predict that
    scatter, so that error bars are calibrated.
    """

    # The noise level of the visibilities corresponds to a system temperature
    # TSYS (in K) for the 100 kHz channels and 10 s integrations of the
    # synthetic data: sigma = TSYS / sqrt(channel width * integration time).
    TSYS = 300.0
    SIGMA = TSYS * 1e3 / np.sqrt(100e3 * 10.0)  # mK
    ANTPAIRS = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3), (0, 4), (1, 4)]

    @pytest.fixture(scope="class")
    def noise_dsets(self, synthetic_uvd):
        """Two independent noise realisations, and their noise levels."""
        kwargs = dict(nfreq=NFREQ, ntimes=500, antpairs=self.ANTPAIRS, sigma=self.SIGMA)
        dsets = [synthetic_uvd(seed=NOISE_SEED + i, **kwargs) for i in range(2)]
        dsets_std = [uvd.copy() for uvd in dsets]
        for uvd in dsets_std:
            uvd.data_array[:] = self.SIGMA
        return dsets, dsets_std

    @pytest.fixture(
        scope="class",
        params=[("I", "none"), ("I", "bh"), ("H^-1", "bh")],
        ids=lambda p: "-".join(p),
    )
    def cross_uvp(self, request, noise_dsets, gauss_beam) -> UVPSpec:
        """Cross-dataset power spectra of every baseline, with the analytic
        covariance of each spectrum."""
        norm, taper = request.param
        dsets, dsets_std = noise_dsets
        ds = PSpecData(
            dsets=dsets, wgts=[None, None], dsets_std=dsets_std, beam=gauss_beam
        )
        return ds.pspec(
            self.ANTPAIRS,
            self.ANTPAIRS,
            dsets=(0, 1),
            pols=[("xx", "xx")],
            norm=norm,
            taper=taper,
            store_cov=True,
            cov_model="dsets",
            verbose=False,
        )

    @staticmethod
    def by_time(values: np.ndarray, uvp: UVPSpec) -> np.ndarray:
        """Reshape (Nbltpairs, ...) values to (Ntimes, Nblpairs, ...): spectra of
        different integrations are independent."""
        order = np.lexsort((uvp.blpair_array, uvp.time_avg_array))
        return values[order].reshape(uvp.Ntimes, uvp.Nblpairs, *values.shape[1:])

    def test_zero_mean(self, cross_uvp) -> None:
        """The cross-power of independent noise has zero mean (real and
        imaginary parts) at every delay."""
        power = cross_uvp.data_array[0][:, :, 0]
        for component in [power.real, power.imag]:
            mean, error = mean_and_error(component, axis=0)
            assert_within_errors(mean, 0.0, error)

    @pytest.mark.parametrize(
        "cross_uvp", [("I", "none"), ("I", "bh")], indirect=True, ids=["I-none", "I-bh"]
    )
    def test_noise_power_matches_p_n(self, cross_uvp) -> None:
        """The rms of the real and of the imaginary parts both equal the noise
        power P_N of generate_noise_spectra(component="real").

        P_N assumes that each delay mode is estimated independently of the
        others, which is the case for norm I with or without a taper. The H^-1
        normalization undoes the correlations introduced by a taper, which
        increases the noise (the covariance test below checks that).
        """
        P_N = cross_uvp.generate_noise_spectra(
            0, ("xx", "xx"), self.TSYS, component="real"
        )
        P_N = np.unique(np.concatenate(list(P_N.values())))
        assert len(P_N) == 1
        power = self.by_time(cross_uvp.data_array[0][:, :, 0], cross_uvp)
        for component in [power.real, power.imag]:
            mean_square, error = mean_and_error(component**2)
            assert_within_errors(mean_square, P_N[0] ** 2, error)

    def test_covariance_matches_scatter(self, cross_uvp) -> None:
        """The diagonal of the analytic covariance equals the variance of the
        real (cov_array_real) and imaginary (cov_array_imag) parts across
        realisations, at every delay; so z-scores P / sigma have unit
        variance."""
        power = cross_uvp.data_array[0][:, :, 0]
        for component, cov in [
            (power.real, cross_uvp.cov_array_real[0]),
            (power.imag, cross_uvp.cov_array_imag[0]),
        ]:
            variance = np.diagonal(cov[..., 0], axis1=1, axis2=2)
            z_squared = component**2 / variance
            mean, error = mean_and_error(z_squared, axis=0)
            assert_within_errors(mean, 1.0, error)
            mean, error = mean_and_error(self.by_time(z_squared, cross_uvp))
            assert_within_errors(mean, 1.0, error)
